-- Extend the India catalogue while retaining every existing vehicle and variant ID.
-- A source documents a manufacturer's configuration. is_verified remains the admin's review flag.
alter table public.vehicle_models
  add column aliases text[] not null default '{}',
  add column market_status text not null default 'unknown'
    check (market_status in ('current', 'discontinued', 'unknown')),
  add column is_electric boolean not null default false;

alter table public.vehicle_variants
  add column generation text check (generation is null or char_length(generation) between 1 and 60),
  add column seating_source_url text
    check (seating_source_url is null or (seating_source_url like 'https://%' and char_length(seating_source_url) <= 600)),
  add constraint vehicle_variants_sourced_seats
    check (seating_source_url is null or passenger_seats = seats_total - 1);

drop index public.vehicle_variants_uidx;
create unique index vehicle_variants_uidx on public.vehicle_variants
  (model_id, coalesce(generation, ''), coalesce(model_year, 0), variant);

